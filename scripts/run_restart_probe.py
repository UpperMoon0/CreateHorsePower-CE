#!/usr/bin/env python3
"""Run two separate server JVMs against one fresh, isolated CHP probe world.

Only CI/test directories created by this script are used. No world is deleted.
Minecraft's EULA acceptance is limited to these user-authorized isolated tests.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile


def properties(path: Path) -> dict[str, str]:
    result = {}
    for line in path.read_text(encoding="iso-8859-1").splitlines():
        if line and not line.startswith(("#", "!")) and "=" in line:
            key, value = line.split("=", 1)
            result[key] = value
    return result


def run(command: list[str], cwd: Path, log: Path, timeout: int) -> None:
    options = {"start_new_session": True} if os.name != "nt" else {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP}
    # .bat files need cmd, with every dynamic argument supplied by argparse choices
    # or an absolute task-local path; no command string is constructed.
    if os.name == "nt":
        command = ["cmd.exe", "/c", *command]
    with log.open("w", encoding="utf-8") as output:
        process = subprocess.Popen(command, cwd=cwd, stdout=output, stderr=subprocess.STDOUT, **options)
        try:
            code = process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            if os.name == "nt":
                subprocess.run(["taskkill.exe", "/PID", str(process.pid), "/T", "/F"], check=False, stdout=output, stderr=subprocess.STDOUT)
            else:
                os.killpg(process.pid, signal.SIGTERM)
            raise RuntimeError(f"Server phase exceeded {timeout}s; see {log}")
    if code:
        raise RuntimeError(f"Server phase exited {code}; see {log}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", choices=["forge-1.20.1", "neoforge-1.21.1"], required=True)
    parser.add_argument("--icy", choices=["true", "false"], required=True)
    parser.add_argument("--timeout", type=int, default=1200)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    evidence_root = root / args.project / "build" / "restart-evidence"
    evidence_root.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix=f"{args.icy}-", dir=evidence_root)).resolve()
    # A fresh generated directory is mandatory; there is no path argument capable
    # of selecting an existing world, and neither phase deletes any files.
    (work / ".chp-isolated-restart-probe").write_text("generated by run_restart_probe.py\n", encoding="utf-8")
    (work / "eula.txt").write_text("eula=true\n", encoding="utf-8")
    generator = {"layers": [{"block": "minecraft:bedrock", "height": 1}, {"block": "minecraft:dirt", "height": 2}, {"block": "minecraft:grass_block", "height": 1}], "biome": "minecraft:plains", "structures": {}}
    settings = {"level-name": "probe-world", "level-type": "minecraft:flat", "generator-settings": json.dumps(generator, separators=(",", ":")), "online-mode": "false", "server-ip": "127.0.0.1", "server-port": "0", "enable-rcon": "false", "enable-query": "false", "spawn-protection": "0", "max-tick-time": "180000", "view-distance": "2", "simulation-distance": "2", "allow-nether": "false", "spawn-monsters": "false", "spawn-animals": "true", "spawn-npcs": "false", "sync-chunk-writes": "true"}
    (work / "server.properties").write_text("".join(f"{k}={v}\n" for k, v in settings.items()), encoding="utf-8")
    wrapper = root / ("gradlew.bat" if os.name == "nt" else "gradlew")
    results = []
    print(f"Isolated restart world and evidence: {work}", flush=True)
    for phase in ["write", "read"]:
        command = [str(wrapper), f":{args.project}:runServer", f"-PicyCompatibilityTest={args.icy}", f"-PchpRestartPhase={phase}", f"-PchpRestartDirectory={work}", "--no-daemon", "--stacktrace", "--max-workers=2"]
        run(command, root, work / f"{phase}.log", args.timeout)
        evidence = work / f"restart-{phase}.properties"
        if not evidence.exists():
            raise RuntimeError(f"No {phase} evidence: probe did not execute; see {work / (phase + '.log')}")
        result = properties(evidence)
        if result.get("status") != "PASS" or result.get("phase") != phase or result.get("icy") != args.icy:
            raise RuntimeError(f"{phase} probe failed: {result}")
        for i in range(2):
            if int(result.get(f"worker.{i}.tickDelta", "0")) < 20 or float(result.get(f"worker.{i}.displacement", "0")) <= 0.02 or abs(float(result.get(f"worker.{i}.rpm", "0"))) <= 0.01:
                raise RuntimeError(f"Missing actual worker tick/orbit/output evidence: {result}")
        results.append(result)
        print(f"{args.project} Icy={args.icy} {phase}: PASS", flush=True)
    if results[0].get("pid") == results[1].get("pid"):
        raise RuntimeError("Restart phases unexpectedly share one JVM PID")
    for i in range(2):
        if results[0].get(f"worker.{i}.chunkUnloaded") != "true" or results[0].get(f"worker.{i}.chunkReloaded") != "true":
            raise RuntimeError("Write phase did not observe real chunk and entity unloading/reloading")
        for field in ["uuid", "crank", "type"]:
            key = f"worker.{i}.{field}"
            if results[0].get(key) != results[1].get(key):
                raise RuntimeError(f"Persisted identity changed: {key}")
        if results[1].get(f"worker.{i}.restoredNoAi") != ("true" if i == 1 else "false"):
            raise RuntimeError("Restart did not restore both original AI baselines")
    (work / "restart-summary.json").write_text(json.dumps({"project": args.project, "icy": args.icy, "status": "PASS", "phases": results}, indent=2), encoding="utf-8")
    print(f"CHP_RESTART_ACCEPTANCE PASS {args.project} icy={args.icy}", flush=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        print(f"CHP_RESTART_ACCEPTANCE FAIL: {error}", file=sys.stderr)
        raise SystemExit(1)
